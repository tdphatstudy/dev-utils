const open = async (id, name) => {
  await page.goto(url + '/#/tool/' + id)
  await page.getByRole('heading', { name, exact: true }).first().waitFor()
  if (id !== 'network.http') await page.locator('.cm-content').first().waitFor()
  else await page.locator('[data-tool-ready="network.http"]').waitFor()
}
const measure = async (tool) => {
  const layout = await page.evaluate(() => ({
    toolbars: [...document.querySelectorAll('.mac-tool-toolbar')].map((element) => Math.round(element.getBoundingClientRect().height)),
    editors: [...document.querySelectorAll('.cm-content')].map((element) => ({ label: element.getAttribute('aria-label'), height: Math.round(element.closest('.cm-editor').getBoundingClientRect().height), top: Math.round(element.getBoundingClientRect().top) }))
  }))
  report.layouts.push({ tool, ...layout })
}
const summary = (label) => page.locator('summary').filter({ hasText: new RegExp('^' + label.replace(/[.*+?^${}()|[\]\\]/g, '\\$&') + '$') })
const editorText = async (label) => {
  await page.evaluate(() => new Promise((done) => requestAnimationFrame(() => requestAnimationFrame(done))))
  const editor = page.getByLabel(label, { exact: true })
  if (await editor.locator('.cm-placeholder').count()) return ''
  return editor.locator('.cm-line').allTextContents().then((lines) => lines.join('\n'))
}
const waitEditor = async (label, expected) => {
  const pattern = expected instanceof RegExp ? expected.source : null
  await page.waitForFunction(({ label, expected, pattern }) => {
    const editor = [...document.querySelectorAll('.cm-content')].find((element) => element.getAttribute('aria-label') === label)
    const value = editor ? editor.querySelector('.cm-placeholder') ? '' : [...editor.querySelectorAll('.cm-line')].map((line) => line.textContent).join('\n') : null
    return value !== null && (pattern ? new RegExp(pattern).test(value) : value === expected)
  }, { label, expected: pattern ? null : expected, pattern })
  return editorText(label)
}
const setEditor = async (label, value) => {
  await page.getByLabel(label, { exact: true }).fill(value)
  await page.waitForFunction(({ label, value }) => [...document.querySelectorAll('.cm-content')].some((element) => element.getAttribute('aria-label') === label && element.textContent === value), { label, value })
}
const visibleEditor = async (label, minimumHeight) => {
  const bounds = await page.getByLabel(label, { exact: true }).evaluate((element) => {
    const box = element.closest('.cm-editor').getBoundingClientRect()
    return { height: box.height, top: box.top, bottom: box.bottom, viewport: innerHeight }
  })
  assert.ok(bounds.height >= minimumHeight, `${label}: editor height ${bounds.height} below ${minimumHeight}`)
  assert.ok(bounds.top >= 48 && bounds.bottom <= bounds.viewport, `${label}: editor not reachable in viewport: ${JSON.stringify(bounds)}`)
}
