import { clipboard, ClipboardItem } from 'electron'
import { MAX_CLIP_IMAGE, MAX_CLIP_TEXT, type ClipContent } from '@shared/clipboard/types'

const secretFormats = ['org.nspasteboard.ConcealedType', 'org.nspasteboard.TransientType', 'org.nspasteboard.AutoGeneratedType', 'x-kde-passwordManagerHint', 'ExcludeClipboardContentFromMonitorProcessing']
const rawFormat = (name: string): string => `electron application/osclipboard;format="${name}"`

export async function readNativeClipboard(): Promise<ClipContent | 'private' | null> {
  // Inspect confidentiality markers before reading the contents, including Windows history opt-out.
  for (const format of secretFormats) if (await clipboard.has(rawFormat(format))) return 'private'
  const items = await clipboard.read()
  if (items.length !== 1) return null // Multi-file/custom clipboard payloads are not flattened silently.
  const item = items[0]
  const historyFlag = rawFormat('CanIncludeInClipboardHistory')
  if (item.types.includes(historyFlag)) {
    const flag = await item.getType(historyFlag)
    if (!(flag instanceof Blob) || flag.size > 16) return 'private'
    const bytes = new Uint8Array(await flag.arrayBuffer())
    if (bytes.length >= 4 && new DataView(bytes.buffer).getUint32(0, true) === 0) return 'private'
  }
  const result: ClipContent = { text: '' }
  for (const type of ['text/plain', 'text/html', 'image/png']) {
    if (!item.types.includes(type)) continue
    const blob = await item.getType(type)
    if (!(blob instanceof Blob)) return null
    if (blob.size > (type === 'image/png' ? MAX_CLIP_IMAGE : MAX_CLIP_TEXT)) return null
    if (type === 'image/png') {
      const bytes = Buffer.from(await blob.arrayBuffer())
      if (!validClipPng(bytes)) return null
      result.png = bytes.toString('base64')
    } else if (type === 'text/html') result.html = await blob.text()
    else result.text = await blob.text()
  }
  return result.text || result.png ? result : null
}
export function validClipPng(bytes: Uint8Array): boolean {
  if (bytes.length < 24 || bytes.length > MAX_CLIP_IMAGE) return false
  const b = Buffer.from(bytes)
  if (!b.subarray(0, 8).equals(Buffer.from([137, 80, 78, 71, 13, 10, 26, 10])) || b.toString('ascii', 12, 16) !== 'IHDR') return false
  const width = b.readUInt32BE(16), height = b.readUInt32BE(20)
  return width > 0 && height > 0 && width * height <= 16_000_000
}
export async function writeNativeClipboard(content: ClipContent, original: boolean): Promise<void> {
  if (!content.png && (!original || !content.html)) { await clipboard.writeText(content.text); return }
  const data: Record<string, string | Blob> = {}
  if (content.text) data['text/plain'] = content.text
  if (original && content.html) data['text/html'] = content.html
  if (content.png) data['image/png'] = new Blob([Uint8Array.from(Buffer.from(content.png, 'base64'))], { type: 'image/png' })
  await clipboard.write([new ClipboardItem(data)])
}
